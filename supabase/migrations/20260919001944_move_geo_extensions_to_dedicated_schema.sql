create schema if not exists extensions;

drop table if exists public.speed_verifications cascade;
drop table if exists public.road_segments cascade;
drop table if exists public.vehicle_profiles cascade;
drop function if exists public.road_segments_near_route(jsonb, double precision);

drop extension if exists pgrouting;
drop extension if exists postgis cascade;

create extension postgis with schema extensions;
create extension pgrouting with schema extensions;

create table public.road_segments (
  id bigint generated by default as identity primary key,
  osm_id bigint,
  name text,
  highway_type text not null,
  maxspeed_mph numeric,
  oneway boolean,
  access text,
  lsv_status text not null default 'unknown'
    check (lsv_status in ('verified_eligible', 'restricted', 'unknown', 'verified_blocked')),
  speed_source text,
  speed_verified_at timestamptz,
  geom extensions.geometry(LineString, 4326) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index road_segments_geom_idx
  on public.road_segments using gist (geom);
create index road_segments_osm_id_idx
  on public.road_segments (osm_id);

create table public.speed_verifications (
  id bigint generated by default as identity primary key,
  road_segment_id bigint not null references public.road_segments(id) on delete cascade,
  source_name text not null,
  source_url text,
  posted_speed_mph numeric not null,
  verified_at timestamptz not null default now(),
  notes text
);

create index speed_verifications_road_segment_id_idx
  on public.speed_verifications (road_segment_id);

create table public.vehicle_profiles (
  id text primary key,
  name text not null,
  max_road_speed_mph numeric not null,
  description text
);

